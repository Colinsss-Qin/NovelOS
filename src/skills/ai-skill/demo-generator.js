/**
 * Generate demo content for a given task type.
 * Returns a simple async generator for SSE compatibility.
 */
async function* demoGenerate(task, opts = {}) {
  const content = DEMO_RESPONSES[task] || DEMO_RESPONSES.chapter_generate;

  // Simulate streaming by yielding one character at a time (speed: ~50 chars/100ms)
  const chars = [...content];
  const batchSize = opts.fast ? 20 : 3;

  for (let i = 0; i < chars.length; i += batchSize) {
    const batch = chars.slice(i, i + batchSize).join("");
    yield batch;
    if (!opts.fast) {
      await new Promise((resolve) => setTimeout(resolve, 20 + Math.random() * 30));
    }
  }
}

